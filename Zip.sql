
CREATE OR REPLACE PROCEDURE FINALIZE_CSV_LOAD (
    P_PROCESSING_ID IN VARCHAR2
)
AS
    V_CATEGORY VARCHAR2(200);
    V_FOLDER   VARCHAR2(500);
    V_COUNT    NUMBER;
BEGIN
    SELECT CSV_CATEGORY, SOURCE_FOLDER_NAME
      INTO V_CATEGORY, V_FOLDER
      FROM CSV_LOAD_LOG
     WHERE PROCESSING_ID = P_PROCESSING_ID
       AND STATUS = 'PROCESSING'
     FOR UPDATE;

    IF UPPER(TRIM(V_CATEGORY)) = 'MANAGER' THEN

        INSERT INTO CASESHIELD_86599CCM_MANAGER
        (
            CASE_ID,
            NOTE,
            NOTE_UPDATED,
            USERID,
            PROCESSING_ID,
            LOAD_DATE,
            SOURCE_FOLDER_NAME
        )
        SELECT
            CASE_ID,
            NOTE,
            NOTE_UPDATED,
            USERID,
            PROCESSING_ID,
            SYSDATE,
            SOURCE_FOLDER_NAME
        FROM STG_CASESHIELD_86599CCM_MANAGER
        WHERE PROCESSING_ID = P_PROCESSING_ID;

        V_COUNT := SQL%ROWCOUNT;

    ELSE
        RAISE_APPLICATION_ERROR(
            -20001,
            'Unsupported CSV category: ' || V_CATEGORY
        );
    END IF;

    UPDATE CSV_LOAD_LOG
       SET STATUS = 'SUCCESS',
           ROWS_LOADED = V_COUNT,
           END_TIME = SYSTIMESTAMP,
           ERROR_MESSAGE = NULL
     WHERE PROCESSING_ID = P_PROCESSING_ID;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END FINALIZE_CSV_LOAD;
/
